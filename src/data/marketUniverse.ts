// Helper to generate realistic historical OHLCV series
export function generateCandles(basePrice: number, count: number = 60, intervalMinutes: number = 5): Candle[] {
  const candles: Candle[] = [];
  let currentClose = basePrice * 0.97;
  const now = Date.now();
  const stepMs = intervalMinutes * 60 * 1000;

  for (let i = count; i >= 0; i--) {
    const timeMs = now - i * stepMs;
    const dateObj = new Date(timeMs);
    const timeStr = `${dateObj.getHours().toString().padStart(2, '0')}:${dateObj.getMinutes().toString().padStart(2, '0')}`;
    
    // Deterministic random walk with slight upward bias
    const volatility = basePrice * 0.004;
    const drift = (Math.sin(i / 6) * 0.4 + (Math.random() - 0.48)) * volatility;
    const open = Number((currentClose).toFixed(2));
    const close = Number(Math.max(1, open + drift).toFixed(2));
    const high = Number(Math.max(open, close, open + Math.random() * volatility * 0.8).toFixed(2));
    const low = Number(Math.min(open, close, open - Math.random() * volatility * 0.8).toFixed(2));
    const volume = Math.floor(25000 + Math.random() * 95000);

    candles.push({
      time: timeStr,
      timestamp: timeMs,
      open,
      high,
      low,
      close,
      volume
    });

    currentClose = close;
  }

  // Anchor last candle close to current basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
    candles[candles.length - 1].high = Math.max(candles[candles.length - 1].high, basePrice);
    candles[candles.length - 1].low = Math.min(candles[candles.length - 1].low, basePrice);
  }

  return candles;
}

