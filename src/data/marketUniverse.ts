// Fallback generator for other tickers
export function getFinancialsForTicker(ticker: string, currentPrice: number): FinancialYearData[] {
  if (FINANCIAL_STATEMENTS[ticker]) {
    return FINANCIAL_STATEMENTS[ticker];
  }
  const factor = Math.max(1, currentPrice / 100);
  return [2025, 2024, 2023, 2022, 2021].map((yr, idx) => {
    const rev = Math.round((58000 + idx * -4200) * factor);
    const gross = Math.round(rev * 0.58);
    const opInc = Math.round(rev * 0.28);
    const netInc = Math.round(rev * 0.22);
    return {
      year: `FY ${yr}`,
      revenue: rev,
      cogs: rev - gross,
      grossProfit: gross,
      rdExpense: Math.round(rev * 0.12),
      sgaExpense: Math.round(rev * 0.18),
      operatingIncome: opInc,
      netIncome: netInc,
      dilutedEps: Number((netInc / 1200).toFixed(2)),
      cashAndEquivalents: Math.round(18000 * factor),
      totalAssets: Math.round(75000 * factor),
      totalDebt: Math.round(15000 * factor),
      stockholderEquity: Math.round(38000 * factor),
      operatingCashFlow: Math.round(opInc * 1.15),
      capitalExpenditures: Math.round(opInc * 0.22),
      freeCashFlow: Math.round(opInc * 0.93),
      grossMarginPct: 58.0 - idx * 0.8,
      operatingMarginPct: 28.0 - idx * 0.6,
      netMarginPct: 22.0 - idx * 0.5,
      roicPct: 21.4 - idx * 0.9,
      roePct: 26.8 - idx * 1.1
    };
  });
}

